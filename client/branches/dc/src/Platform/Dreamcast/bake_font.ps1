# Bake a glyph atlas into a C++ source file for the Dreamcast build.
# Uses GDI+ (System.Drawing) to rasterize Arial at a fixed pixel size.
param(
    [string]$FontName = "Arial",
    [int]$PixelSize = 16,
    [string]$Out = "C:\Users\usuario\Desktop\mu online\Mu-Linux-0.97.43\client\branches\dc\src\Platform\Dreamcast\DCFontBaked.cpp"
)

Add-Type -AssemblyName System.Drawing

$codepoints = @()
for ($c = 32; $c -le 126; $c++) { $codepoints += $c }
for ($c = 161; $c -le 255; $c++) { $codepoints += $c }

$bmp = New-Object System.Drawing.Bitmap(96, 48)
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.Clear([System.Drawing.Color]::Black)
$g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
$font = New-Object System.Drawing.Font($FontName, $PixelSize, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
$fmt = [System.Drawing.StringFormat]::GenericTypographic
$brush = [System.Drawing.Brushes]::White

# Baseline position of a GDI+ DrawString at y=0 (cell ascent scaled to pixel size).
$fam = $font.FontFamily
$ascent = $fam.GetCellAscent([System.Drawing.FontStyle]::Regular)
$emHeight = $fam.GetEmHeight([System.Drawing.FontStyle]::Regular)
$baselineY = [math]::Round(($PixelSize * $ascent) / $emHeight)

$covLines = @()
$entryLines = @()

foreach ($cp in $codepoints) {
    $ch = [char]$cp
    $s = [string]$ch
    $g.Clear([System.Drawing.Color]::Black)
    if ($cp -ne 32) {
        $g.DrawString($s, $font, $brush, 0, 0, $fmt)
    }
    $minX = 999; $minY = 999; $maxX = -1; $maxY = -1
    for ($y = 0; $y -lt 48; $y++) {
        for ($x = 0; $x -lt 96; $x++) {
            $p = $bmp.GetPixel($x, $y)
            if ($p.R -gt 32) {
                if ($x -lt $minX) { $minX = $x }
                if ($x -gt $maxX) { $maxX = $x }
                if ($y -lt $minY) { $minY = $y }
                if ($y -gt $maxY) { $maxY = $y }
            }
        }
    }
    if ($maxX -lt 0) { $minX = 0; $minY = 0; $maxX = 0; $maxY = 0 }
    $w = $maxX - $minX + 1
    $h = $maxY - $minY + 1
    if ($cp -eq 32) { $w = 0; $h = 0; $minX = 0; $minY = 0 }

    $sz = $g.MeasureString($s, $font, 9999, $fmt)
    $advance = [int][math]::Round($sz.Width)
    if ($cp -eq 32) { $advance = [int][math]::Round($PixelSize * 0.28) }
    if ($advance -lt 1) { $advance = 1 }

    $arrName = ("g_cov_{0:X4}" -f $cp)
    $covSize = [math]::Max(1, $w * $h)
    $covLines += "static const uint8_t $arrName" + '[' + $covSize + '] = {'
    if ($w -gt 0 -and $h -gt 0) {
        $vals = @()
        for ($y = $minY; $y -le $maxY; $y++) {
            for ($x = $minX; $x -le $maxX; $x++) {
                $p = $bmp.GetPixel($x, $y)
                $vals += $(if ($p.R -gt 32) { '255' } else { '0' })
            }
        }
        for ($i = 0; $i -lt $vals.Count; $i += 24) {
            $end = [math]::Min($i + 23, $vals.Count - 1)
            $covLines += '    ' + ($vals[$i..$end] -join ',') + ','
        }
    }
    $covLines += '};'

    $glyphTop = [math]::Max(0, $baselineY - $minY)
    $safeLeft = [math]::Max(0, $minX)
    $safeAdv = [math]::Max(1, [math]::Min(255, $advance))
    $safeTop = [math]::Min(255, $glyphTop)
    $display = if ($cp -ge 32 -and $cp -le 126) { $ch } else { '?' }
    $entryLines += ("    {{0x{0:X4}, {1}, {2}, {3}, {4}, {5}, {6}}}, // U+{0:X4} '{7}'" -f $cp, $safeAdv, $safeLeft, $safeTop, $w, $h, $arrName, $display)
}

$lines = @()
$lines += '// AUTO-GENERATED by bake_font.ps1 - do not edit by hand.'
$lines += '// Pre-baked glyph coverage for the Dreamcast build (no runtime FreeType).'
$lines += '#include "Platform/Dreamcast/DCFont.h"'
$lines += ''
$lines += 'namespace Platform {'
$lines += 'namespace {'
$lines += 'struct BakedGlyph { uint16_t cp; uint8_t advance, left, top, w, h; const uint8_t* cov; };'
$lines += ''
$lines += $covLines
$lines += ''
$lines += 'static const BakedGlyph kGlyphs[] = {'
$lines += $entryLines
$lines += '};'
$lines += ''
$lines += 'const BakedGlyph* BakedGlyphFor(uint32_t cp) {'
$lines += '    for (const BakedGlyph& g : kGlyphs) if (g.cp == cp) return &g;'
$lines += '    return nullptr;'
$lines += '}'
$lines += '} // namespace'
$lines += ''
$lines += 'bool DCFont_BakedGlyph(uint32_t cp, int& advance, int& left, int& top,'
$lines += '                      int& w, int& h, const uint8_t*& cov) {'
$lines += '    const BakedGlyph* g = BakedGlyphFor(cp);'
$lines += '    if (!g) return false;'
$lines += '    advance = g->advance; left = g->left; top = g->top;'
$lines += '    w = g->w; h = g->h; cov = g->cov;'
$lines += '    return true;'
$lines += '}'
$lines += ''
$lines += '} // namespace Platform'
$lines += ''

[System.IO.File]::WriteAllText($Out, ($lines -join "`r`n"), [System.Text.Encoding]::ASCII)
$g.Dispose(); $font.Dispose(); $bmp.Dispose()
Write-Host "WROTE $Out"
Write-Host "GLYPHS=$($codepoints.Count) BYTES=$((Get-Item $Out).Length)"
